"""
=========================================================
📅 日期: 2026-10-27
📚 章节: 廖雪峰 - 5.1 数据类型和变量
💡 核心结论与 Java 视角对比：
1. 整数：Python 支持任意大小整数（Java 有 int/long 限制），且支持用 `_` 分隔数字方便阅读。
2. 浮点数：存在精度丢失问题（和 Java 的 float/double 一样），涉及金额计算建议用 Decimal。
3. 字符串：单双引号等价，支持三引号多行字符串，支持 r 前缀表示原始字符串。
=========================================================
"""

# ==========================================
# 1. 整数 (Integers)
# ==========================================
# Python 可以处理任意大小的整数，不需要像 Java 那样声明 int 或 long
a = 100
b = -8080
c = 0

# 十六进制表示，用 0x 前缀
hex_num = 0xff00
print("十六进制 0xff00 的十进制是:", hex_num)

# Python 特有的语法糖：用下划线 _ 分隔大数字，不影响数值大小
# 类似 Java 7 引入的 10_000_000
big_num = 10_000_000_000
print("大数字:", big_num)

# ==========================================
# 2. 浮点数 (Floating-Point Numbers)
# ==========================================
# 科学计数法表示 (把 10 用 e 替代)
sci_num1 = 1.23e9    # 等于 1.23 * 10^9
sci_num2 = 0.000012  # 等于 1.2e-5
print("科学计数法:", sci_num1)

# ⚠️ 重点坑：浮点数运算可能会有四舍五入的误差
# 无论是在 Python 还是 Java，0.1 + 0.2 都不绝对等于 0.3
print("0.1 + 0.2 =", 0.1 + 0.2)
# 如果要做精确计算（如金额），Python 使用 decimal 模块，Java 使用 BigDecimal

# ==========================================
# 3. 字符串 (Strings)
# ==========================================
# 单引号和双引号完全等价
str1 = 'abc'
str2 = "xyz"

# 如果字符串内部包含单引号，外面就用双引号；反之亦然
str3 = "I'm OK"
print(str3)

# 转义字符 \ (和 Java 完全一致)
str4 = 'I\'m \"OK\"!'
print(str4)

# 取消转义 (Raw String)：在字符串前加 r
# 这在写正则表达式或 Windows 文件路径时极度好用！
print('普通的换行符: \n')
print(r'加了 r 之后: \n') # 直接打印出 \n 字符本身

# 多行字符串：使用三个单引号 ''' 或三个双引号 """ 括起来
# Java 需要用到 Java 15 才引入的 Text Blocks (""") 才能实现类似效果
multi_line_str = '''第一行
第二行
第三行'''
print(multi_line_str)


# ==========================================
# 4. 变量与动态类型
# ==========================================
# Java 是强类型静态语言 (String a = "hello";)
# Python 是动态语言，变量本身没有类型，类型属于对象
var_test = 123
print(type(var_test)) # <class 'int'>

var_test = "hello" # 同一个变量可以随时变成字符串类型
print(type(var_test)) # <class 'str'>