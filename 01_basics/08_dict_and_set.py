# 💡 任务 12：为什么 dict 的查找速度极快，而 list 查找速度慢？
# 你的心得：dict 底层是哈希表，为了做到极速查找，它在内存中开辟了更多的空间来维护索引。而 list 是连续的内存块，非常紧凑。这就是典型的空间换时间。
# 当你把不可变的 key 存进去时，Python 会通过 Hash 算法（哈希函数） 算出一个数字，直接根据这个数字算出它存放在内存的哪个“抽屉”里。下次找它，直接拿 key 一算，瞬间拉开那个抽屉。这个过程几乎是瞬间完成的（时间复杂度 O(1)）。